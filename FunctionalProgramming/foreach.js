// Criando um array com quatro elementos (strings)
const array = [ "A", "B", "C", "D" ];

// Usando forEach para percorrer cada elemento do array
// A função "e => console.log(...)" será chamada para cada item
// "e" representa o elemento atual do array
array.forEach(e => console.log("Element: " + e));

// Resultado no console:
// Element: A
// Element: B
// Element: C
// Element: D